#!/usr/bin/env python3
"""Pin Waydroid to CPU rendering. See waydroid.nix for the why."""
import configparser
import os
import sys

WORK = "/var/lib/waydroid"
CFG = os.path.join(WORK, "waydroid.cfg")
BASE_PROP = os.path.join(WORK, "waydroid_base.prop")

PROPS = {
    "ro.hardware.gralloc": "default",
    "ro.hardware.egl": "angle",
    "ro.hardware.vulkan": "pastel",
}

if not os.path.isfile(CFG):
    # `waydroid init` hasn't run yet, so there is nothing to seed.
    sys.exit(0)

cp = configparser.ConfigParser()
cp.optionxform = str  # Android property names are case-sensitive
cp.read(CFG)
if not cp.has_section("properties"):
    cp.add_section("properties")
if any(cp.get("properties", k, fallback=None) != v for k, v in PROPS.items()):
    for k, v in PROPS.items():
        cp.set("properties", k, v)
    with open(CFG, "w") as f:
        cp.write(f)

# waydroid_base.prop is only regenerated by `waydroid init` / `waydroid upgrade`,
# but it is what a session start actually reads (helpers/images.py:make_prop), so
# keep it in sync here rather than shelling out to `waydroid upgrade -o`.
if os.path.isfile(BASE_PROP):
    with open(BASE_PROP) as f:
        lines = f.read().splitlines()
    kept = [ln for ln in lines if ln.split("=", 1)[0].strip() not in PROPS]
    updated = kept + [f"{k}={v}" for k, v in PROPS.items()]
    if updated != lines:
        with open(BASE_PROP, "w") as f:
            f.write("\n".join(updated) + "\n")
        os.chmod(BASE_PROP, 0o644)
